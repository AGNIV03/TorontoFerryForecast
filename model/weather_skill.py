"""Choose the weather forecast model per lead time by measured skill at the terminal.

Archived forecasts (Open-Meteo Previous Runs, value predicted 24*N h before valid time)
are scored against Billy Bishop observations (QC'd) for daytime hours 06-23 local on the
common period where all candidate models exist. Variables: temperature, wind speed,
relative humidity, hourly precipitation (amount MAE and wet-hour detection >= 0.2 mm) and
daytime precipitation totals. Each variable's MAE is divided by the mean MAE across models
for that N, and the normalised scores are averaged (lower = better). The best single model
and the mean of the top-2 / top-3 models are compared, and the winner per N is written to
data/models/weather_models.json.

    python -m model.weather_skill
"""

from __future__ import annotations

import json
from itertools import combinations

import numpy as np
import pandas as pd

from common import db
from common.config import MODELS, REPORTS

MAIN = ["ecmwf_ifs025", "gem_seamless", "gfs_seamless", "icon_seamless"]
EXTRA = ["gem_hrdps_continental", "ecmwf_ifs"]
VARS = {"temp_c": "temperature_2m", "wind_kmh": "wind_speed_10m", "rh": "relative_humidity_2m",
        "precip_mm": "precipitation"}
BUCKETS = {"<=24h (N=0-1)": [0, 1], "24-72h (N=2-3)": [2, 3], "3-7 days (N=4-7)": [4, 5, 6, 7]}


def scores(f: pd.DataFrame, obs: pd.DataFrame) -> dict:
    j = f.merge(obs, on="ts_utc", how="inner")
    loc = j.ts_utc.dt.tz_convert("America/Toronto")
    j = j[(loc.dt.hour >= 6)]
    out = {}
    for o, m in VARS.items():
        out[f"{o}_mae"] = float(np.nanmean(np.abs(j[o] - j[m])))
    wet_o, wet_f = j.precip_mm >= 0.2, j.precipitation >= 0.2
    hits = (wet_o & wet_f).sum()
    out["wet_hour_csi"] = float(hits / max((wet_o | wet_f).sum(), 1))
    d = j.assign(day=loc[j.index].dt.date).groupby("day")[["precip_mm", "precipitation"]].sum(min_count=12)
    out["day_precip_mae"] = float(np.nanmean(np.abs(d.precip_mm - d.precipitation)))
    out["n_hours"] = int(len(j))
    return out


def main():
    pr = db.table("om_previous_runs")
    obs = db.table("weather_obs")[["ts_utc", "temp_c", "wind_kmh", "rh", "precip_mm", "precip_mm_src"]]
    obs = obs[obs.precip_mm_src.isin(["eccc_cc", "eccc_city"])]
    rows = []
    # common period for the main models, per N
    for n in range(8):
        p = pr[pr.lead_day == n]
        # models that exist at this N (ICON has no 7-day-old forecasts: its runs end at 180 h)
        avail = [m for m in MAIN if (p.model == m).sum() > 24 * 60]
        sets = [set(p[p.model == m].dropna(subset=list(VARS.values())).ts_utc) for m in avail]
        common = set.intersection(*sets) if sets and all(sets) else set()
        if not common:
            continue
        cands = {m: p[(p.model == m) & p.ts_utc.isin(common)] for m in avail}
        for m, f in cands.items():
            rows.append({"N": n, "model": m, **scores(f, obs)})
        # blends of 2 and 3 models
        for k in range(2, len(avail) + 1):
            for combo in combinations(avail, k):
                g = pd.concat([cands[m] for m in combo]).groupby("ts_utc")[list(VARS.values())].mean().reset_index()
                rows.append({"N": n, "model": "+".join(combo), **scores(g, obs)})
        # extra short-range / high-res models on their own (shorter) overlap, for information
        for m in EXTRA:
            f = p[p.model == m].dropna(subset=list(VARS.values()))
            if len(f) > 24 * 60:
                rows.append({"N": n, "model": m + " (own period)", **scores(f, obs)})
    s = pd.DataFrame(rows)
    mae_cols = ["temp_c_mae", "wind_kmh_mae", "rh_mae", "precip_mm_mae", "day_precip_mae"]
    main_rows = ~s.model.str.contains("own period")
    for c in mae_cols:
        s.loc[main_rows, c + "_n"] = s[main_rows][c] / s[main_rows].groupby("N")[c].transform("mean")
    s.loc[main_rows, "csi_n"] = s[main_rows].groupby("N").wet_hour_csi.transform("mean") / s[main_rows].wet_hour_csi
    s["score"] = s[[c + "_n" for c in mae_cols] + ["csi_n"]].mean(axis=1)
    best = s[main_rows].sort_values("score").groupby("N").head(1).set_index("N")
    by_n = {int(n): r.model.split("+") for n, r in best.iterrows()}
    MODELS.mkdir(parents=True, exist_ok=True)
    (MODELS / "weather_models.json").write_text(json.dumps({"by_n": by_n}, indent=2))

    # report
    lines = ["# Weather forecast model selection\n",
             "_Generated by `python -m model.weather_skill`._\n",
             "Archived forecasts from the Open-Meteo Previous Runs API (value predicted 24 x N h before valid time), "
             "scored against Billy Bishop observations (06:00-23:59 local) over the period common to all four global "
             "models (Feb 2024 onwards). Lower MAE is better; CSI = critical success index for wet hours "
             "(>= 0.2 mm), higher is better. `score` is the mean of MAEs normalised by the average across models "
             "for that N (and inverted CSI): below 1 = better than average.\n"]
    singles = s[s.model.isin(MAIN)]
    for b, ns in BUCKETS.items():
        t = singles[singles.N.isin(ns)].groupby("model")[mae_cols + ["wet_hour_csi", "score"]].mean().sort_values("score")
        lines += [f"\n## Single models, {b}\n", t.to_markdown(floatfmt=".3f")]
    t = s[main_rows].groupby("model")[["score"] + mae_cols + ["wet_hour_csi"]].mean().sort_values("score").head(8)
    lines += ["\n## Best singles and blends, averaged over N = 0-7\n", t.to_markdown(floatfmt=".3f")]
    t = best[["model", "score", "temp_c_mae", "precip_mm_mae", "day_precip_mae", "wet_hour_csi", "n_hours"]]
    lines += ["\n## Selected per N (used for the honest backtest and live predictions)\n", t.to_markdown(floatfmt=".3f")]
    ex = s[s.model.str.contains("own period")][["N", "model", "temp_c_mae", "wind_kmh_mae", "precip_mm_mae",
                                                 "wet_hour_csi", "n_hours"]]
    if len(ex):
        ref = singles[singles.N.isin(ex.N.unique())].groupby(["N", "model"])[["temp_c_mae", "precip_mm_mae", "wet_hour_csi"]].mean()
        lines += ["\n## High-resolution models (own, shorter periods; not directly comparable)\n",
                  ex.to_markdown(index=False, floatfmt=".3f"),
                  "\nGlobal models over the full common period, for reference:\n", ref.to_markdown(floatfmt=".3f")]
    (REPORTS / "weather_model_selection.md").write_text("\n".join(lines), encoding="utf-8")
    print(best[["model", "score"]])


if __name__ == "__main__":
    main()
