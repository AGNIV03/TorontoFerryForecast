"""Metric tables for the model report -> reports/model_report_tables.md

    python -m reports.make_model_report
"""

from __future__ import annotations

import numpy as np
import pandas as pd

from common import db
from common.config import PROCESSED, REPORTS
from model.core import LEVELS, mae, mape, wape

METHODS = {"pred": "LightGBM", "bl_seasonal_naive": "Seasonal naive (4 wk)",
           "bl_last_year": "Same day last year", "bl_climatology": "Climatology"}
BUCKET = {0: "0-1 d", 1: "0-1 d", 2: "2-3 d", 3: "2-3 d", 4: "4-7 d", 5: "4-7 d", 6: "4-7 d", 7: "4-7 d"}


def hourly_table(r: pd.DataFrame, by: list[str]) -> pd.DataFrame:
    rows = []
    for k, g in r.groupby(by, observed=True):
        k = k if isinstance(k, tuple) else (k,)
        d = dict(zip(by, k))
        for c, name in METHODS.items():
            d[f"WAPE {name}"] = wape(g.y, g[c])
        d["MAE LightGBM"] = mae(g.y, g.pred)
        d["MAE best baseline"] = min(mae(g.y, g[c]) for c in METHODS if c != "pred")
        d["hours"] = len(g)
        rows.append(d)
    return pd.DataFrame(rows)


def daily(r: pd.DataFrame) -> pd.DataFrame:
    g = r.groupby(["fold", "mode", "issue_date", "target_date", "lead"])
    d = g.agg(y=("y", "sum"), n=("y", "size"), **{c: (c, "sum") for c in METHODS},
              season=("season", "first"), is_weekend=("is_weekend", "first"),
              is_holiday=("is_holiday", "first"), holiday_kind=("holiday_kind", "first"),
              d_precip=("d_precip", "first"), d_tmax=("d_tmax", "first")).reset_index()
    return d[d.n == 18]


def daily_table(d: pd.DataFrame, by: list[str]) -> pd.DataFrame:
    rows = []
    for k, g in d.groupby(by, observed=True):
        k = k if isinstance(k, tuple) else (k,)
        row = dict(zip(by, k))
        for c, name in METHODS.items():
            row[f"MAPE {name}"] = mape(g.y, g[c])
        row["days"] = len(g)
        rows.append(row)
    return pd.DataFrame(rows)


def main():
    r = pd.read_parquet(PROCESSED / "backtest.parquet")
    r["lead_bucket"] = r.lead.map(BUCKET)
    r["day_type"] = np.where((r.is_weekend == 1) | (r.is_holiday == 1), "weekend/holiday", "weekday")
    r["season2"] = np.where(r.season == "peak", "peak (Jun-Labour Day)", "off-season")
    fc_keys = r[r["mode"] == "fc"][["issue_date", "target_date", "hour"]].drop_duplicates()
    obs_same = r[r["mode"] == "obs"].merge(fc_keys, on=["issue_date", "target_date", "hour"])
    obs_same["mode"] = "obs (same rows as fc)"
    rr = pd.concat([r, obs_same], ignore_index=True)

    out = ["# Model report: metric tables\n", "_Generated by `python -m reports.make_model_report` from "
           "`data/processed/backtest.parquet`._\n",
           "Hourly metrics cover operating hours 06:00-23:59 local. WAPE = sum|error| / sum(actual). "
           "Mode `obs` = observed weather (ceiling); `fc` = archived real forecasts (honest, from Feb 2024); "
           "`obs (same rows as fc)` = the ceiling restricted to exactly the rows where `fc` exists, for a like-for-like gap.\n"]
    p = out.append
    fmt = dict(index=False, floatfmt=".3f")
    p("## 1. Overall, hourly\n")
    p(hourly_table(rr, ["mode"]).to_markdown(**fmt))
    p("\n## 2. By test year\n")
    p(hourly_table(rr, ["mode", "fold"]).to_markdown(**fmt))
    p("\n## 3. By lead time\n")
    p(hourly_table(rr, ["mode", "lead_bucket"]).to_markdown(**fmt))
    p("\n### Per lead day (fc mode)\n")
    p(hourly_table(rr[rr["mode"] == "fc"], ["lead"]).to_markdown(**fmt))
    p("\n## 4. Peak season vs off-season\n")
    p(hourly_table(rr, ["mode", "season2"]).to_markdown(**fmt))
    p("\n## 5. Weekends/holidays vs weekdays\n")
    p(hourly_table(rr, ["mode", "day_type"]).to_markdown(**fmt))
    p("\n## 6. Season x day type x lead (fc mode)\n")
    p(hourly_table(rr[rr["mode"] == "fc"], ["season2", "day_type", "lead_bucket"]).to_markdown(**fmt))

    d = daily(rr)
    d["lead_bucket"] = d.lead.map(BUCKET)
    d["season2"] = np.where(d.season == "peak", "peak (Jun-Labour Day)", "off-season")
    d["day_type"] = np.where((d.is_weekend == 1) | (d.is_holiday == 1), "weekend/holiday", "weekday")
    p("\n## 7. Daily totals (sum of hours 06-23): MAPE\n")
    p(daily_table(d, ["mode"]).to_markdown(**fmt))
    p("\n")
    p(daily_table(d, ["mode", "lead_bucket"]).to_markdown(**fmt))
    p("\n")
    p(daily_table(d, ["mode", "season2", "day_type"]).to_markdown(**fmt))

    p("\n## 8. Busyness levels\n")
    p("Default scheme `capacity` (`config/busyness.json`, `config/capacity.json`): boardings as a share of the "
      "practical hourly capacity of the ferry schedule in force (winter / spring / summer / peak summer / fall, "
      "plus dated overrides such as a vessel out of service). Quiet < 25% <= Moderate < 50% <= Busy < 80% <= "
      "Very busy. Percentile variants are compared below. The predicted level is the level of the point forecast.\n")
    lk = rr.drop_duplicates(["target_date", "hour"])
    p("\nShare of holdout hours at each level (actuals), by schedule period:\n")
    p(pd.crosstab(lk.level_key, lk.level_true.map(dict(enumerate(LEVELS))), normalize="index")
      .reindex(columns=LEVELS).fillna(0).to_markdown(floatfmt=".2f"))
    p("")
    rows = []
    for (m, b), g in rr.groupby(["mode", "lead_bucket"]):
        rows.append({"mode": m, "lead_bucket": b,
                     "exact LightGBM": (g.level_pred == g.level_true).mean(),
                     "within 1 LightGBM": (abs(g.level_pred - g.level_true) <= 1).mean(),
                     "exact seasonal naive": (g.level_sn == g.level_true).mean(),
                     "exact climatology": (g.level_clim == g.level_true).mean(),
                     "hours": len(g)})
    p(pd.DataFrame(rows).to_markdown(**fmt))
    rows = []
    for (m, b), g in rr.groupby(["mode", "lead_bucket"]):
        rows.append({"mode": m, "lead_bucket": b, "exact LightGBM": (g.level_pred_h == g.level_true_h).mean(),
                     "within 1 LightGBM": (abs(g.level_pred_h - g.level_true_h) <= 1).mean(),
                     "exact climatology": (g.level_clim_h == g.level_true_h).mean(), "hours": len(g)})
    p("\nSame metrics with the per-season-and-hour definition from the original spec (`scheme: season_hour`):\n")
    p(pd.DataFrame(rows).to_markdown(**fmt))
    rows = []
    for (m, b), g in rr.groupby(["mode", "lead_bucket"]):
        rows.append({"mode": m, "lead_bucket": b, "exact LightGBM": (g.level_pred_s == g.level_true_s).mean(),
                     "within 1 LightGBM": (abs(g.level_pred_s - g.level_true_s) <= 1).mean(),
                     "exact climatology": (g.level_clim_s == g.level_true_s).mean(), "hours": len(g)})
    p("\nOne year-round percentile scale (`scheme: all`):\n")
    p(pd.DataFrame(rows).to_markdown(**fmt))
    for m in ["obs", "fc"]:
        g = rr[rr["mode"] == m]
        cm = pd.crosstab(pd.Categorical(g.level_true.map(dict(enumerate(LEVELS))), LEVELS),
                         pd.Categorical(g.level_pred.map(dict(enumerate(LEVELS))), LEVELS),
                         rownames=["actual"], colnames=["predicted"], dropna=False)
        p(f"\nConfusion matrix ({m}, all leads; rows = actual):\n")
        p(cm.to_markdown())
        p("\nRow-normalised:\n")
        p((cm.div(cm.sum(axis=1), axis=0)).to_markdown(floatfmt=".2f"))

    p("\n## 9. Prediction intervals (p10-p90, nominal 80%)\n")
    rows = []
    for (m, b, s), g in rr.groupby(["mode", "lead_bucket", "season2"]):
        rows.append({"mode": m, "lead": b, "season": s, "coverage": ((g.y >= g.p10) & (g.y <= g.p90)).mean(),
                     "below p10": (g.y < g.p10).mean(), "above p90": (g.y > g.p90).mean(),
                     "mean width": (g.p90 - g.p10).mean(), "mean actual": g.y.mean()})
    p(pd.DataFrame(rows).to_markdown(**fmt))

    from model.core import apply_interval_calibration, fit_interval_calibration
    p("\n### 9b. After split-conformal recalibration (fc mode; each test year calibrated only on earlier years)\n")
    p("Raw quantile-model ranges are too narrow with forecast weather (above). Each side of the range is widened "
      "per (lead day, peak season) so that 10% of calibration actuals fall below and 10% above. 2025 is calibrated "
      "on 2024's errors, 2026 on 2024-2025's. 2024 has no earlier forecast-mode year, so it is omitted.\n")
    fcm = r[r["mode"] == "fc"].copy()
    rows = []
    for fold in ("2025", "2026"):
        calib = fit_interval_calibration(fcm[fcm.fold < fold])
        g = fcm[fcm.fold == fold].copy()
        g["p10"], g["p90"] = apply_interval_calibration(g, calib)
        for (b, s), gg in g.groupby(["lead_bucket", "season2"]):
            rows.append({"test year": fold, "lead": b, "season": s,
                         "coverage": ((gg.y >= gg.p10) & (gg.y <= gg.p90)).mean(),
                         "below p10": (gg.y < gg.p10).mean(), "above p90": (gg.y > gg.p90).mean(),
                         "mean width": (gg.p90 - gg.p10).mean()})
    p(pd.DataFrame(rows).to_markdown(**fmt))
    from common.config import MODELS
    MODELS.mkdir(parents=True, exist_ok=True)
    prod_cal = fit_interval_calibration(fcm)
    (MODELS / "interval_calibration.json").write_text(__import__("json").dumps(prod_cal, indent=1))
    p("\nProduction calibration (fit on all forecast-mode backtest rows, 2024-2026), scale factors applied to the "
      "raw p10/p90 distances:\n")
    p(pd.DataFrame(prod_cal).T.rename_axis("lead|peak").to_markdown(floatfmt=".2f"))

    p("\n## 10. Feature importance (gain, share of total; mean over folds)\n")
    imps = pd.concat([pd.read_csv(f) for f in sorted(PROCESSED.glob("importance_*.csv"))])
    imps["share"] = imps.gain / imps.groupby("fold").gain.transform("sum")
    t = imps.groupby("feature").share.mean().sort_values(ascending=False)
    p(t.head(30).to_frame().to_markdown(floatfmt=".3f"))

    p("\n## 11. The 20 worst-predicted days (fc mode, issued the day before = lead 1)\n")
    w = d[(d["mode"] == "fc") & (d.lead == 1)].copy()
    w["err"] = w.pred - w.y
    w["abs_err"] = w.err.abs()
    w["pct_err"] = w.err / w.y
    obsd = d[(d["mode"] == "obs") & (d.lead == 1)][["target_date", "pred", "d_precip", "d_tmax"]].rename(
        columns={"pred": "pred_obs_wx", "d_precip": "obs_precip", "d_tmax": "obs_tmax"})
    w = w.merge(obsd, on="target_date", how="left")
    fh = db.table("ferry_hourly")
    flags = fh.groupby("date").agg(bulk_intervals=("bulk_flag", "sum")).reset_index().rename(columns={"date": "target_date"})
    w = w.merge(flags, on="target_date", how="left")
    w = w.sort_values("abs_err", ascending=False).head(20)
    w["dow"] = pd.to_datetime(w.target_date).dt.day_name().str[:3]
    cols = ["target_date", "dow", "holiday_kind", "y", "pred", "pct_err", "pred_obs_wx", "d_precip", "obs_precip",
            "d_tmax", "obs_tmax", "bulk_intervals"]
    t = w[cols].rename(columns={"y": "actual", "pred": "pred (fc wx)", "d_precip": "fc precip mm",
                                 "d_tmax": "fc tmax", "pred_obs_wx": "pred (obs wx)"})
    t["target_date"] = pd.to_datetime(t.target_date).dt.date
    p(t.to_markdown(index=False, floatfmt=".1f"))

    p("\n## 12. Same-day adjustment (nowcast), lead 0, fc mode\n")
    p("At clock time c, hours 06..c-1 have been counted (the feed lags ~1 h; hour c is in progress). "
      "Remaining hours c+1..23 are scaled by clip((actual so far + k) / (predicted so far + k), 0.5, 1.8). "
      "k = 400 was chosen a priori; other values shown for sensitivity.\n")
    z = rr[(rr["mode"] == "fc") & (rr.lead == 0)]
    rows = []
    for c in (10, 12, 14, 16):
        for k in (0, 200, 400, 800):
            num_raw = num_adj = den = 0.0
            for _, g in z.groupby("target_date"):
                g = g.set_index("hour")
                if len(g) < 18:
                    continue
                known = g.loc[6:c - 1]
                rest = g.loc[c + 1:23]
                f = 1.0 if k == 0 and known.pred.sum() == 0 else np.clip(
                    (known.y.sum() + k) / (known.pred.sum() + k), 0.5, 1.8)
                num_raw += np.abs(rest.y - rest.pred).sum()
                num_adj += np.abs(rest.y - rest.pred * f).sum()
                den += rest.y.sum()
            rows.append({"clock time": f"{c}:00", "k": k, "WAPE remaining, unadjusted": num_raw / den,
                         "WAPE remaining, adjusted": num_adj / den})
    p(pd.DataFrame(rows).to_markdown(index=False, floatfmt=".3f"))

    # daily error quantiles by lead (fc mode) -> used for the published daily ranges
    dq = {}
    for lead, g in d[d["mode"] == "fc"].groupby("lead"):
        e = (g.y - g.pred) / g.pred.clip(lower=1)
        dq[str(int(lead))] = {"q10": round(float(e.quantile(0.1)), 3), "q90": round(float(e.quantile(0.9)), 3)}
    from common.config import MODELS
    MODELS.mkdir(parents=True, exist_ok=True)
    (MODELS / "daily_error_quantiles.json").write_text(__import__("json").dumps(dq, indent=1))
    p("\n## 13. Daily-total ranges (fc mode): 10th/90th percentile of (actual - forecast) / forecast\n")
    p(pd.DataFrame(dq).T.rename_axis("lead").to_markdown(floatfmt=".3f"))
    (REPORTS / "model_report_tables.md").write_text("\n".join(out), encoding="utf-8")
    print("wrote", REPORTS / "model_report_tables.md")


if __name__ == "__main__":
    main()
